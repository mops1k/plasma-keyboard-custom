"""Builds the swipe engine's word lists from the predictive word lists.

The swipe engine (src/swipekb, MIT) reads AOSP `.combined` dictionaries. The
keyboard already ships FrequencyWords word lists with corpus frequencies as
PKD1 resources (src/prediction/data, MIT, generated by
tools/generate-prediction-dictionaries.sh), so the swipe dictionaries are cut
from those: the same words, the same frequencies, the most frequent `--top`
of them, in the format the engine expects.

Two transformations are needed:

  * letters only. The swipe engine walks a trie of key sequences, so a word is
    reachable only when every letter of it has a key. Apostrophes are kept for
    English (the engine adds them back for "dont"); Russian has no apostrophe
    and «ё» is typed with the «е» key, so «ё» is folded into «е».
  * AOSP's 0..255 frequency. The corpus counts are folded the way AOSP's own
    lists are: f = 27.5 * zipf - 1, where zipf is log10 occurrences per billion
    words (the constants are the ones the upstream Swipe Keyboard project uses
    to put AOSP-frequency words on its scale).

Usage:
  tools/generate-swipe-dictionaries.py --out DIR [--langs "en ru"] [--top N]
"""

import argparse
import math
import os
import struct
import sys

LANGUAGES = {
    "en": {"letters": set("abcdefghijklmnopqrstuvwxyz'"), "fold": {}},
    "ru": {"letters": set("абвгдежзийклмнопрстуфхцчшщъыьэюя"), "fold": {"ё": "е"}},
}


def read_pkd1(path):
    """[(word, frequency)] of a PKD1 word list, in file order."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"PKD1":
        raise SystemExit("%s: not a PKD1 word list" % path)
    count = struct.unpack_from("<I", data, 4)[0]
    offsets = struct.unpack_from("<%dI" % (count + 1), data, 8)
    pool = 8 + (count + 1) * 4
    pool_data = data[pool:pool + offsets[-1]]
    frequencies = struct.unpack_from("<%dI" % count, data, pool + offsets[-1])
    words = []
    for i in range(count):
        raw = pool_data[offsets[i]:offsets[i + 1]].decode("utf-8", "ignore")
        words.append((raw, frequencies[i]))
    return words


def zipf_to_frequency(count, corpus):
    """AOSP's 0..255 frequency, as the upstream project maps wordfreq onto it."""
    zipf = math.log10(max(count, 1) / corpus * 1e9)
    return max(1, min(255, round(27.5 * zipf - 1)))


def build_language(language, words, top):
    profile = LANGUAGES[language]
    letters = profile["letters"]
    fold = profile["fold"]

    corpus = sum(count for _, count in words) or 1
    best = {}
    for word, count in words:
        if not 2 <= len(word) <= 24 or count <= 0:
            continue
        lowered = word.lower()
        folded = "".join(fold.get(c, c) for c in lowered)
        if not folded or any(c not in letters for c in folded):
            continue
        if best.get(folded, 0) < count:
            best[folded] = count

    selected = sorted(best.items(), key=lambda item: (-item[1], item[0]))[:top]
    return [
        (word, zipf_to_frequency(count, corpus), count)
        for word, count in selected
    ]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="directory for the .combined files")
    parser.add_argument("--data", default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "src", "prediction", "data"), help="directory with the PKD1 word lists")
    parser.add_argument("--langs", default="en ru")
    parser.add_argument("--top", type=int, default=50000,
                        help="words per language, most frequent first (0 = all)")
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)
    for language in args.langs.split():
        source = os.path.join(args.data, "%s.bin" % language)
        if not os.path.exists(source):
            print("no word list for %s (%s), skipped" % (language, source), file=sys.stderr)
            continue
        words = build_language(language, read_pkd1(source), args.top or 1 << 62)
        target = os.path.join(args.out, "%s.combined" % language)
        with open(target, "w", encoding="utf-8") as f:
            f.write("dictionary=main:%s,locale=%s,description=plasma-keyboard-custom,"
                    "date=0,version=54\n" % (language, language))
            for word, frequency, original in words:
                f.write(" word=%s,f=%d,flags=,originalFreq=%d\n" % (word, frequency, original))
        print("%s: %d words -> %s" % (language, len(words), target))


if __name__ == "__main__":
    main()
